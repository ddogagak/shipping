import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';

const compile=(name)=>ts.transpileModule(readFileSync(new URL(`./src/lib/${name}.ts`,import.meta.url),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const url=code=>`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`;
let source=compile('inventory-investment');
for(const dep of ['pricing','sale-units','item-analysis-series'])source=source.replaceAll(`"./${dep}"`,`"${url(compile(dep))}"`);
const {buildInvestmentReport,orderCapital,analysisBoxCost,purchaseDay}=await import(url(source));
assert.equal(orderCapital({currency:'JPY',paid_amount:1000,local_shipping:0,raw_data:{}}).cost,62000);
assert.equal(orderCapital({currency:'JPY',paid_amount:120000,local_shipping:20000,raw_data:{payment_currency:'KRW',invoice_total_confirmed:true,first_payment:100000,second_payment_confirmed:true}}).cost,120000);
